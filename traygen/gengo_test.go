func TestGoName(t *testing.T) {
	cases := map[string]string{
		"idle":      "Idle",
		"no-badge":  "NoBadge",
		"has_error": "HasError",
		"running2":  "Running2",
	}
	for in, want := range cases {
		if got := goName(in); got != want {
			t.Errorf("goName(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestGenerateGo(t *testing.T) {
	cfg := loadTestConfig(t)
	out := t.TempDir()
	if err := GenerateGo(cfg, out); err != nil {
		t.Fatalf("GenerateGo: %v", err)
	}

	data, err := os.ReadFile(filepath.Join(out, "icons_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	src := string(data)

	for _, want := range []string{
		"// Code generated by traygen. DO NOT EDIT.",
		"package trayicons",
		"//go:embed dark/linux-png-fallback light/linux-png-fallback",
		"func Icon(dark bool, status Status) ([]byte, error)",
		"func ForStatus(status Status) tray.IconsFunc",
		`"github.com/smegg99/s99wails/v2/shell/tray"`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("generated code missing %q\n---\n%s", want, src)
		}
	}

	// Check const definitions with whitespace tolerance for gofmt alignment.
	for _, pattern := range []string{
		`StatusIdle\s+Status = "idle"`,
		`StatusRunning\s+Status = "running"`,
		`StatusError\s+Status = "error"`,
	} {
		if !regexp.MustCompile(pattern).MatchString(src) {
			t.Errorf("generated code missing pattern %q\n---\n%s", pattern, src)
		}
	}

	// Must be parseable Go.
	if _, err := parser.ParseFile(token.NewFileSet(), "icons_gen.go", data, 0); err != nil {
		t.Errorf("generated code does not parse: %v", err)
	}

	// Generated code must be gofmt-canonical.
	formatted, err := format.Source(data)
	if err != nil {
		t.Fatalf("format.Source: %v", err)
	}
	if !bytes.Equal(formatted, data) {
		t.Error("generated code is not gofmt-canonical")
	}
}

func TestGenerateGoWithoutAdapter(t *testing.T) {
	cfg := loadTestConfig(t)
	cfg.TrayAdapter = false
	out := t.TempDir()
	if err := GenerateGo(cfg, out); err != nil {
		t.Fatal(err)
	}
	data, _ := os.ReadFile(filepath.Join(out, "icons_gen.go"))
	if strings.Contains(string(data), "s99wails/tray") {
		t.Error("trayAdapter=false must not import s99wails/tray")
	}
}

func TestGoNameUnicode(t *testing.T) {
	if got := goName("żółty-badge"); got != "ŻółtyBadge" {
		t.Errorf("goName(żółty-badge) = %q, want ŻółtyBadge", got)
	}
}

func TestGenerateGoRejectsCollidingStates(t *testing.T) {
	cfg := loadTestConfig(t)
	cfg.States["no-badge"] = State{}
	cfg.States["no_badge"] = State{}
	if err := GenerateGo(cfg, t.TempDir()); err == nil {
		t.Error("colliding state identifiers must error")
	}
}

func TestGenerateGoRejectsEmptyIdentifier(t *testing.T) {
	cfg := loadTestConfig(t)
	cfg.States["-"] = State{}
	if err := GenerateGo(cfg, t.TempDir()); err == nil {
		t.Error("separator-only state name must error")
	}
}
