// traygen/gengo.go

package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/dave/jennifer/jen"
)

// goName converts a state name to an exported Go identifier suffix:
// "no-badge" -> "NoBadge".
func goName(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '-' || r == '_' })
	var b strings.Builder
	for _, p := range parts {
		runes := []rune(p)
		b.WriteString(strings.ToUpper(string(runes[0])) + string(runes[1:]))
	}
	return b.String()
}

type genState struct {
	Name, GoName string
}

// GenerateGo writes icons_gen.go next to the generated assets.
func GenerateGo(cfg *Config, outDir string) error {
	states := make([]genState, 0, len(cfg.States))
	seen := map[string]string{}
	for _, name := range cfg.StateNames() {
		gn := goName(name)
		if gn == "" {
			return fmt.Errorf("state %q produces an empty Go identifier", name)
		}
		if prev, ok := seen[gn]; ok {
			return fmt.Errorf("states %q and %q both map to Go identifier Status%s", prev, name, gn)
		}
		seen[gn] = name
		states = append(states, genState{Name: name, GoName: gn})
	}

	f := jen.NewFile(cfg.GoPackage)
	f.HeaderComment("Code generated by traygen. DO NOT EDIT.")
	// Suppresses jennifer's redundant alias on the tray import.
	f.ImportName("github.com/smegg99/s99wails/tray", "tray")

	f.Comment("Status selects a pregenerated tray icon state.")
	f.Type().Id("Status").String()

	f.Const().DefsFunc(func(g *jen.Group) {
		for _, s := range states {
			g.Id("Status" + s.GoName).Id("Status").Op("=").Lit(s.Name)
		}
	})

	embedDirs := make([]string, 0, len(cfg.Themes))
	for _, theme := range cfg.ThemeNames() {
		embedDirs = append(embedDirs, theme+"/linux-png-fallback")
	}
	f.Comment("//go:embed " + strings.Join(embedDirs, " "))
	f.Var().Id("FS").Qual("embed", "FS")

	f.Comment("Icon returns the primary-size PNG for the theme/status combination.")
	f.Func().Id("Icon").
		Params(jen.Id("dark").Bool(), jen.Id("status").Id("Status")).
		Params(jen.Index().Byte(), jen.Error()).
		Block(
			jen.Id("theme").Op(":=").Lit("light"),
			jen.If(jen.Id("dark")).Block(
				jen.Id("theme").Op("=").Lit("dark"),
			),
			jen.Return(jen.Id("FS").Dot("ReadFile").Call(
				jen.Qual("fmt", "Sprintf").Call(
					jen.Lit("%s/linux-png-fallback/"+cfg.Prefix+"-%s-%s.png"),
					jen.Id("theme"), jen.Id("theme"), jen.Id("status"),
				),
			)),
		)

	if cfg.TrayAdapter {
		f.Comment("ForStatus adapts a status to the s99wails tray icon interface:")
		f.Comment("")
		f.Comment("\tmanager.SetIcons(ForStatus(StatusError))")
		f.Func().Id("ForStatus").
			Params(jen.Id("status").Id("Status")).
			Qual("github.com/smegg99/s99wails/tray", "IconsFunc").
			Block(
				jen.Return(jen.Func().
					Params(jen.Id("dark").Bool()).
					Params(jen.Index().Byte(), jen.Error()).
					Block(
						jen.Return(jen.Id("Icon").Call(jen.Id("dark"), jen.Id("status"))),
					),
				),
			)
	}

	var buf bytes.Buffer
	if err := f.Render(&buf); err != nil {
		return fmt.Errorf("render generated code: %w", err)
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("gofmt generated code: %w", err)
	}
	if err := os.WriteFile(filepath.Join(outDir, "icons_gen.go"), src, 0o644); err != nil {
		return fmt.Errorf("write icons_gen.go: %w", err)
	}
	return nil
}
