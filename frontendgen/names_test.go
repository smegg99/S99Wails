var update = flag.Bool("update", false, "rewrite assets/names.ts from the Go constants")

// shared is every name the emitted TypeScript uses with Go: a const's value, or a type's Wails service path.
var shared = []struct{ ts, dir, goName, doc string }{
	{"CRASH_SERVICE", "shell/crash", "type Service", "The shell/crash.Service path for Call.ByName."},
	{"CRASH_HEARTBEAT", "shell/crash", "type Heartbeat", "The shell/crash.Heartbeat path for Call.ByName."},
	{"CRASH_QUERY", "shell/crash", "Query", "The URL query key that marks the crash screen's window."},
	{"CRASH_REPORT_EVENT", "shell/crash", "reportEvent", "Carries each new crash report while the screen is open."},
	{"EDIT_KEY_EVENT", "shell/editkeys", "Event", "Carries an undo or redo key the native window took."},
	{"THEME_CHANGED_EVENT", "services/theme", "EventThemeChanged", "Emitted by the services/theme watcher."},
	{"WINDOWS_CHANGED_EVENT", "shell/windows", "eventWindowsChanged", "Carries the window list after it changes."},
	{"TAB_ARRIVE_EVENT", "shell/windows", "eventTabArrive", "Offers a tab to the window it moves to."},
	{"TAB_RELEASE_EVENT", "shell/windows", "eventTabRelease", "Tells the source window a claimed tab may go."},
	{"TAB_DONE_EVENT", "shell/windows", "eventTabDone", "Ends a transfer on both windows."},
	{"TAB_CANCEL_EVENT", "shell/windows", "eventTabCancel", "Tells the target window a transfer was cancelled."},
	{"TAB_CANCELLED_EVENT", "shell/windows", "eventTabCancelled", "Gives the source window its cancelled offer back."},
	{"TAB_HOVER_EVENT", "shell/windows", "eventTabHover", "Carries the drop a dragged tab would make, or null."},
	{"TAB_TRACK_EVENT", "shell/windows", "eventTabTrack", "Carries the pointer over the drag's source window."},
	{"TAB_DRAG_END_EVENT", "shell/windows", "eventTabDragEnd", "Ends a drag with the tab left in place."},
	{"TAB_DROP_EVENT", "shell/windows", "eventTabDrop", "Carries where a dragged tab was dropped."},
	{"WINDOW_BLOCKED_EVENT", "shell/windows", "eventWindowBlocked", "Carries the message key of a close a window refused."},
	{"WINDOW_RESUME_EVENT", "shell/windows", "eventWindowResume", "Ends a close the user or a window cancelled."},
	{"WINDOW_CLOSE_EVENT", "shell/windows", "eventWindowClose", "Asks a window to flush and confirm its close."},
}

// names renders assets/names.ts from the Go sources under root.
func names(root string) (string, error) {
	var out strings.Builder
	out.WriteString("// frontendgen/assets/names.ts\n")
	out.WriteString("// Code generated by `just names` from the Go constants. DO NOT EDIT.\n")
	mod, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return "", err
	}
	module, _, _ := strings.Cut(strings.TrimPrefix(string(mod), "module "), "\n")
	packages := map[string][]*ast.File{}
	for _, name := range shared {
		files, ok := packages[name.dir]
		if !ok {
			var err error
			if files, err = parse(filepath.Join(root, name.dir)); err != nil {
				return "", err
			}
			packages[name.dir] = files
		}
		value, err := lookup(files, module+"/"+name.dir, name.goName)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&out, "\n/** %s */\nexport const %s = '%s'\n", name.doc, name.ts, value)
	}
	return out.String(), nil
}

// parse reads the package's non-test Go files in dir.
func parse(dir string) ([]*ast.File, error) {
	paths, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	var files []*ast.File
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			return nil, err
		}
		files = append(files, file)
	}
	return files, nil
}

// lookup finds a string const's value in the package at path, or for "type X" the Wails service path of X.
func lookup(files []*ast.File, path, name string) (string, error) {
	typeName, isType := strings.CutPrefix(name, "type ")
	for _, file := range files {
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, spec := range gen.Specs {
				switch spec := spec.(type) {
				case *ast.TypeSpec:
					if isType && spec.Name.Name == typeName {
						return path + "." + typeName, nil
					}
				case *ast.ValueSpec:
					for i, ident := range spec.Names {
						if isType || ident.Name != name || i >= len(spec.Values) {
							continue
						}
						lit, ok := spec.Values[i].(*ast.BasicLit)
						if !ok || lit.Kind != token.STRING {
							return "", fmt.Errorf("%s.%s is not a string literal", path, name)
						}
						return strconv.Unquote(lit.Value)
					}
				}
			}
		}
	}
	return "", fmt.Errorf("%s has no %s", path, name)
}

// The TypeScript names shared with Go are generated from the Go constants, never typed twice.
func TestNamesFollowTheGoConstants(t *testing.T) {
	want, err := names("..")
	if err != nil {
		t.Fatal(err)
	}
	if *update {
		if err := os.WriteFile("assets/names.ts", []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile("assets/names.ts")
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Fatalf("assets/names.ts is stale; run `just names`:\n%s", want)
	}
}
