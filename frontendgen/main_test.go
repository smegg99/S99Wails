package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestRunEmitsComposables(t *testing.T) {
	out := t.TempDir()
	if err := run(filepath.Join(out, "s99wails"), false); err != nil {
		t.Fatalf("run: %v", err)
	}

	for file, marker := range map[string]string{
		"index.ts":       "useDesktopLocaleSync",
		"environment.ts": "'_wails' in window",
		"localeSync.ts":  "getLanguage",
		"systemTheme.ts": "theme:changed",
		"logBridge.ts":   "unhandledrejection",
		"appTitle.ts":    "useAppTitle",
	} {
		data, err := os.ReadFile(filepath.Join(out, "s99wails", file))
		if err != nil {
			t.Errorf("missing %s: %v", file, err)
			continue
		}
		src := string(data)
		if !strings.HasPrefix(src, "// Code generated by s99wails frontendgen. DO NOT EDIT.") {
			t.Errorf("%s missing generated header", file)
		}
		if !strings.Contains(src, marker) {
			t.Errorf("%s missing expected content %q", file, marker)
		}
	}
}

// The s99ab bridge is opt-in: absent by default so a non-s99ab app is not
// handed a file it cannot resolve, present with -s99ab.
func TestS99abBridgeIsOptIn(t *testing.T) {
	bridge := "appearanceBridge.ts"

	base := t.TempDir()
	if err := run(base, false); err != nil {
		t.Fatalf("run(base): %v", err)
	}
	if _, err := os.Stat(filepath.Join(base, bridge)); !os.IsNotExist(err) {
		t.Errorf("bridge emitted without -s99ab (err=%v), want absent", err)
	}

	opted := t.TempDir()
	if err := run(opted, true); err != nil {
		t.Fatalf("run(s99ab): %v", err)
	}
	data, err := os.ReadFile(filepath.Join(opted, bridge))
	if err != nil {
		t.Fatalf("bridge missing with -s99ab: %v", err)
	}
	src := string(data)
	if !strings.HasPrefix(src, "// Code generated by s99wails frontendgen. DO NOT EDIT.") {
		t.Error("bridge missing generated header")
	}
	if !strings.Contains(src, "@smegg99/s99ab/appearance") {
		t.Error("bridge does not import the s99ab appearance seam")
	}
	// The base composables must still land next to it, since the bridge imports
	// ./systemTheme.
	if _, err := os.Stat(filepath.Join(opted, "systemTheme.ts")); err != nil {
		t.Errorf("systemTheme.ts not emitted alongside the bridge: %v", err)
	}
}
