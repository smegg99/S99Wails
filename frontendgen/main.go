// main.go
//
// frontendgen writes the s99wails Vue composables (runtime detection,
// desktop locale sync, system theme, frontend log bridge) into an app's
// frontend tree, version-locked to this module. Consume as a tool
// dependency next to your composables:
//
//	//go:generate go tool frontendgen -out s99wails
//
// The emitted files import only vue and @wailsio/runtime; anything
// app-specific (binding services) is injected by the caller.
package main

import (
	"embed"
	"flag"
	"fmt"
	"io/fs"
	"log"
	"os"
	"path/filepath"
)

//go:embed assets
var assets embed.FS

const header = "// Code generated by s99wails frontendgen. DO NOT EDIT.\n\n"

func main() {
	out := flag.String("out", "s99wails", "output directory for the emitted composables")
	flag.Parse()

	if err := run(*out); err != nil {
		log.Fatal(err)
	}
}

func run(outDir string) error {
	entries, err := fs.ReadDir(assets, "assets")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf("create %s: %w", outDir, err)
	}

	for _, entry := range entries {
		data, err := fs.ReadFile(assets, "assets/"+entry.Name())
		if err != nil {
			return err
		}
		path := filepath.Join(outDir, entry.Name())
		if err := os.WriteFile(path, append([]byte(header), data...), 0o644); err != nil {
			return fmt.Errorf("write %s: %w", path, err)
		}
	}

	fmt.Printf("frontendgen: %d files -> %s\n", len(entries), outDir)
	return nil
}
