// frontendgen/main.go

// frontendgen writes the s99wails Vue composables into an app's frontend tree:
//
//	//go:generate go tool frontendgen --out s99wails
//	//go:generate go tool frontendgen --out s99wails --s99ab
package main

import (
	"context"
	"embed"
	"fmt"
	"io/fs"
	"os"
	"os/signal"
	"path/filepath"
	"strconv"
	"syscall"

	"github.com/nicksnyder/go-i18n/v2/i18n"
	"github.com/smegg99/s99term"
	"github.com/spf13/cobra"

	"github.com/smegg99/s99wails/v2/internal/cli"
	"github.com/smegg99/s99wails/v2/internal/cli/catalog"
)

//go:embed assets
var assets embed.FS

//go:embed integrations
var integrations embed.FS

const header = "// Code generated by s99wails frontendgen. DO NOT EDIT.\n\n"

func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	a := cli.New(os.Stderr, os.Stdout, os.Environ())
	code := a.Run(ctx, newRoot(a), os.Args[1:])
	stop()
	os.Exit(code)
}

func newRoot(a *cli.App) *cobra.Command {
	var outDir string
	var withS99ab bool
	cmd := &cobra.Command{
		Use:  "frontendgen",
		Args: a.NoArgs,
		RunE: func(*cobra.Command, []string) error {
			n, err := run(outDir, withS99ab)
			if err != nil {
				return err
			}
			a.Console().Line(s99term.StatusOK, catalog.FrontendgenEmitted(a.Say()),
				s99term.F("files", strconv.Itoa(n)), s99term.F("out", outDir))
			return nil
		},
	}
	cmd.Flags().StringVar(&outDir, "out", "s99wails", "")
	cmd.Flags().BoolVar(&withS99ab, "s99ab", false, "")
	a.Describe(func(l *i18n.Localizer) {
		cmd.Short = catalog.FrontendgenShort(l)
		cmd.Long = catalog.FrontendgenLong(l)
		cmd.Flags().Lookup("out").Usage = catalog.FrontendgenFlagOut(l)
		cmd.Flags().Lookup("s99ab").Usage = catalog.FrontendgenFlagS99ab(l)
	})
	return a.Root(cmd)
}

// run emits the composables into outDir, and the s99ab bridges with withS99ab; it returns the file count.
func run(outDir string, withS99ab bool) (int, error) {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return 0, fmt.Errorf("create %s: %w", outDir, err)
	}
	n, err := emit(assets, "assets", outDir)
	if err != nil {
		return 0, err
	}
	// Opt-in: the bridges import @smegg99/s99ab.
	if withS99ab {
		m, err := emit(integrations, "integrations/s99ab", outDir)
		if err != nil {
			return 0, err
		}
		n += m
	}
	return n, nil
}

// emit copies every file in dir into outDir with the generated header.
func emit(fsys embed.FS, dir, outDir string) (int, error) {
	entries, err := fs.ReadDir(fsys, dir)
	if err != nil {
		return 0, err
	}
	for _, entry := range entries {
		data, err := fs.ReadFile(fsys, dir+"/"+entry.Name())
		if err != nil {
			return 0, err
		}
		path := filepath.Join(outDir, entry.Name())
		if err := os.WriteFile(path, append([]byte(header), data...), 0o644); err != nil {
			return 0, fmt.Errorf("write %s: %w", path, err)
		}
	}
	return len(entries), nil
}
